// Step95: trace where an amdgpu CS ioctl fails (RADV "The CS has been rejected (-1)", -EPERM, on submits that
// carry userptr BOs; it took WindowServer down on 2026-11-03). Each listed call site inside amdgpu_cs_ioctl and its
// stages goes through a thunk that logs "NMX cs-trace: <site> -> <errno>" when the callee fails; the drm ioctl return
// in linux_file_ioctl logs every -EPERM. Innermost failing site prints first. Budgets: 96 lines for EPERM,
// 48 for other errors; -EDEADLK (drm_exec retry), -ERESTARTSYS and -EINTR are not logged.
typedef unsigned long u64; typedef unsigned int u32;
#pragma GCC visibility push(hidden)
extern int SNPRINTF(char *buf, u64 n, const char *fmt, ...);
extern int PRINTF(const char *fmt, ...);
extern const char FMT_S[];
extern u32 BUDGET_EPERM, BUDGET_OTHER;   // ci_init_smc_table.__ratelimited (CI dpm only, never runs on Strix)
#pragma GCC visibility pop
static const char names[][18] = { "p1_user_fence", "p1_ib", "p1_bo_handles", "job_alloc", "ctx_get_entity", "syncobj_in", "syncobj_in2", "ib_get", "parser_bos", "patch_jobs", "vm_handling", "sync_rings", "submit", "bos.list_get", "bos.lock_pd", "bos.prepare_obj", "bos.prepare_obj2", "bos.userptr_valid", "bos.list_create", "bos.vm_validate", "bos.bo_validate", "bos.alloc_gart", "vm.clear_freed", "vm.bo_update", "vm.bo_update2", "vm.bo_update3", "vm.handle_moved", "vm.update_pdes", "sync.wait_prev", "sync.resv", "userptr_tail", "ioctl", "userptr_ro_retry" };
void cs_report(int site, int r)
{
    if (r == -35 || r == -512 || r == -4) return;
    u32 *b = r == -1 ? &BUDGET_EPERM : &BUDGET_OTHER;
    if (*b >= (r == -1 ? 96u : 48u)) return;
    (*b)++;
    char s[128];
    SNPRINTF(s, sizeof s, "NMX cs-trace: %s -> %d", (u32)site < sizeof names / sizeof names[0] ? names[site] : "?", r);
    PRINTF(FMT_S, s);
}
// Step96: a writable pin of a read-only mapping fails (-EFAULT from the IOMemoryDescriptor prepare): WindowServer maps
// client CoreAnimation surfaces r--/r-- (SM=SHM) and some assets as read-only files, and libdrm always asks for a
// writable userptr. Retry once read-only and mark the TT read-only (amdgpu_ttm_tt userflags bit 0 at ttm+0x58, the
// bit amdgpu_ttm_tt_pte_flags / is_readonly test), so the GPU maps the pages without WRITEABLE: same as upstream
// AMDGPU_GEM_USERPTR_READONLY. A GPU write then faults instead of landing in someone else's pages.
struct userptr_args { u64 addr, size; u32 flags, handle; };
#pragma GCC visibility push(hidden)
extern int T30(char *tbo, struct userptr_args *a, void *filp);   // userptr_tail (Step92 cave)
#pragma GCC visibility pop
int userptr_ro(char *tbo, struct userptr_args *a, void *filp)
{
    int r = T30(tbo, a, filp);
    if (r != -14 || (a->flags & 1)) return r;
    char *ttm = *(char **)(tbo + 0x1d8);
    if (!ttm) return r;
    a->flags |= 1;                 // userptr_tail pins without FOLL_WRITE
    *(u32 *)(ttm + 0x58) |= 1;     // gtt->userflags |= AMDGPU_GEM_USERPTR_READONLY
    r = T30(tbo, a, filp);
    cs_report(32, r);              // "userptr_ro_retry -> 0" when the read-only pin worked
    return r;
}
