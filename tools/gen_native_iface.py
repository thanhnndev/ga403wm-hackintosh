"""Generate kexts/itlmt7925Native/itlmt7925_iface_stubs.inc from the verified header IO80211InfraProtocol.h.

The Family's request routing calls 190 pure virtuals of IO80211InfraProtocol (slots 467-656) plus IO80211SkywalkInterface::
setMacAddress (slot 417, the 191st pure slot). A native interface must override every one of them or the class stays abstract.
Stage 2 has no radio, so each handler records the call (itlmtCall, kind 'S', id = slot) and answers kIOReturnUnsupported. The declarations are written from the header line by line
(name, parameter list, slot comment), so a regenerated header regenerates the stubs.

  python3 tools/gen_native_iface.py            # rewrite the .inc
  python3 tools/gen_native_iface.py --check    # exit 1 if the committed .inc differs
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDRS = [os.path.join(ROOT, 'kexts/itlmt7925/io80211', h) for h in ('IO80211SkywalkInterface.h', 'IO80211InfraProtocol.h')]
OUT = os.path.join(ROOT, 'kexts/itlmt7925Native/itlmt7925_iface_stubs.inc')
PURE = re.compile(r'/\*\s*(\d+)\s*\*/\s*virtual\s+(\S+)\s+(\w+)\((.*?)\)\s*=\s*0;')
# implemented outside this generated file: setMacAddress with the native station identity; the rest with layouts taken from
# Apple's AppleBCMWLANCore handlers (itlmt7925_iface.cpp, "IO80211InfraProtocol handlers with layouts taken from Apple's ...")
CUSTOM = {'setMacAddress', 'getCHANNEL', 'getPOWERSAVE', 'getRATE', 'getOP_MODE', 'getRSSI', 'setUSB_HOST_NOTIFICATION',
          'setOS_FEATURE_FLAGS', 'setINFRA_ENUMERATED', 'getSUPPORTED_CHANNELS', 'getHW_SUPPORTED_CHANNELS', 'getWCL_BSS_INFO',
          'setWCL_SCAN_REQ', 'setWCL_SCAN_ABORT', 'setWCL_ASSOCIATE', 'setWCL_LEAVE_NETWORK', 'setWCL_JOIN_ABORT',
          'getWCL_LOW_LATENCY_INFO', 'setWCL_SET_SCAN_HOME_AWAY_TIME', 'setWCL_WNM_OPS', 'setWCL_TRIGGER_CC',
          'setWCL_LINK_UP_DONE', 'setWCL_LINK_STATE_UPDATE', 'getWCL_EXTENDED_BSS_INFO', 'setWCL_UPDATE_FAST_LANE',
          'getWCL_TRAFFIC_COUNTERS', 'setPM_MODE', 'setWCL_ARP_MODE', 'setWCL_QOS_PARAMS', 'setWCL_SET_ROAM_LOCK',
          'getNSS', 'setVIRTUAL_IF_CREATE'}


def pure_slots():
    out = []
    for h in HDRS:
        for line in open(h):
            m = PURE.search(line)
            if m:
                out.append((int(m.group(1)), m.group(2), m.group(3), m.group(4)))
    return sorted(out)


def render():
    slots = pure_slots()
    for _, ret, _, _ in slots:
        assert ret == 'IOReturn', ret       # every pure slot returns IOReturn in the header (guess tagged there)
    o = ['// GENERATED by tools/gen_native_iface.py from IO80211SkywalkInterface.h + IO80211InfraProtocol.h. Do not edit by hand.',
         '// %d pure virtual declarations; default handlers unsupported, custom implementations excluded from definitions.' % len(slots),
         '#ifdef ITL_IFACE_DECLS']
    for slot, ret, name, params in slots:
        o.append('    %s %s(%s) override;   // slot %d' % (ret, name, params, slot))
    o.append('#endif')
    o.append('#ifdef ITL_IFACE_DEFS')
    for slot, ret, name, params in slots:
        if name in CUSTOM:
            continue
        # unnamed parameters: the body never touches them
        # every call is counted by slot (itlmtCall kind 'S'): which handlers userland really reaches is what the next round needs
        o.append('%s itlmt7925WifiInterface::%s(%s) { itlmtCall(ctl, \'S\', %d); return kIOReturnUnsupported; }' % (ret, name, params, slot))
    o.append('#endif')
    return '\n'.join(o) + '\n'


def main():
    text = render()
    if '--check' in sys.argv:
        return 0 if open(OUT).read() == text else 1
    open(OUT, 'w').write(text)
    print('wrote %s (%d slots)' % (os.path.relpath(OUT, ROOT), len(pure_slots())))
    return 0


if __name__ == '__main__':
    sys.exit(main())
